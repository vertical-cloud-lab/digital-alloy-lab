    tb.text(0.01, 0.52, "AMAZEMET rePowder collection cup, lab-built (issue #269)", fontsize=9, transform=tb.transAxes)
    tb.text(0.01, 0.28, "Units mm. General tolerances ISO 2768-mK. Break sharp edges 0.2-0.5.", fontsize=8,
            transform=tb.transAxes)
    tb.text(0.01, 0.07, "Third-angle projection. Sizes from params.py (vendor drawings in bom/, photos in dims/).",
            fontsize=7, transform=tb.transAxes)
    import textwrap
