def sheet_a(pdf):
    kf, a = P.JOINT, P.A
    fig, ax = sheet("A: catalogue cup (interim, small charges only)", 4,
                    "KF-50 nipple, blank, ring, clamp: 304; liner 304 tube; puck 304 (2 in bar)",
                    ["Only ~150 cm3 above the puck: Al runs and Cu-alloy charges up to ~250 g (thermal FEA).",
                     "Both joints get an over-pressure ring (A&N 4000076); the bottom O-ring sees the pile.",
                     "Liner: 1-3/4 in x 0.049 tube cut to length, deburred; stands on the puck.",
                     "Puck stands on the blank's recess floor, inside the centring ring."])
    g = kf.ring_thk / 2
    top = -g
    bot = top - a["nipple_len"]
    up = PT.kf_flange_profile(kf, top, down=True, tube_len=a["nipple_len"] / 2)
    lo = PT.kf_flange_profile(kf, bot, down=False, tube_len=a["nipple_len"] / 2)
    section_fill(ax, up)
    section_fill(ax, lo)
    blank_face = bot - 2 * g
    rf, rh = kf.flange_od / 2, kf.hub_od / 2
    t_edge = kf.lip - (rf - rh) * math.tan(math.radians(kf.taper_deg))
    rr, rd = kf.recess_d / 2, kf.recess_depth
    section_fill(ax, [(0, blank_face - rd), (rr, blank_face - rd), (rr, blank_face), (rf, blank_face),
                      (rf, blank_face - t_edge), (rh, blank_face - kf.lip), (0, blank_face - kf.lip)], color="0.75")
    pz = blank_face - rd + 0.2
    section_fill(ax, [(0, pz), (a["puck_d"] / 2, pz), (a["puck_d"] / 2, pz + a["puck_h"]), (0, pz + a["puck_h"])],
                 color="0.95")
    lz0, lz1 = pz + a["puck_h"] + 0.2, top - a["liner_gap_top"]
    section_fill(ax, [(a["liner_od"] / 2 - a["liner_wall"], lz0), (a["liner_od"] / 2, lz0), (a["liner_od"] / 2, lz1),
                      (a["liner_od"] / 2 - a["liner_wall"], lz1)], color="0.95")
    centreline(ax, blank_face - 20, 15)
    x = rf + 18
    dim_v(ax, x, bot, top, f"{a['nipple_len']:.0f} face to face (Duniway KF50-NP)")
    dim_v(ax, x + 22, lz0, lz1, f"liner {lz1 - lz0:.1f}", fs=6.5)
    dim_v(ax, -rf - 18, pz, pz + a["puck_h"], f"puck Ø{a['puck_d']:.0f} x {a['puck_h']:.0f}", side=-1, fs=6.5)
    dim_h(ax, -rf, rf, top + 8, f"Ø{kf.flange_od:.2f}")
    ax.text(rf + 50, top - 20, "Parts\n1 KF-50 full nipple 160 (Duniway KF50-NP)\n2 KF-50 blank (Duniway KF50-FB)\n"
            "3 centring ring SS/FKM (MDC 710003)\n4 KF-50 clamp (Duniway KF50-CP)\n5 over-pressure ring x2 (A&N 4000076)\n"
            "6 liner 1-3/4 x 0.049 304 (McMaster 11116N835)\n7 puck Ø44 x 30, 304", fontsize=8, va="top")
    ax.set_xlim(-110, 250)
    ax.set_ylim(blank_face - 30, top + 25)
    pdf.savefig(fig)
    fig.savefig(OUT / "sheet4_A_catalogue.png", dpi=110)
    plt.close(fig)


