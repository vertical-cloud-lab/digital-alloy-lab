def dim_v(ax, x, y0, y1, text, side=1, off=0.0, fs=7.5):
    ax.annotate("", xy=(x, y0), xytext=(x, y1), arrowprops=dict(arrowstyle="<->", lw=0.6, shrinkA=0, shrinkB=0))
    ax.text(x + side * (1.5 + off), (y0 + y1) / 2, text, fontsize=fs, rotation=90, va="center",
            ha="left" if side > 0 else "right")


def dim_h(ax, x0, x1, y, text, fs=7.5, above=True):
    ax.annotate("", xy=(x0, y), xytext=(x1, y), arrowprops=dict(arrowstyle="<->", lw=0.6, shrinkA=0, shrinkB=0))
    ax.text((x0 + x1) / 2, y + (1.2 if above else -1.2), text, fontsize=fs, ha="center",
            va="bottom" if above else "top")


def ext(ax, p0, p1):
    ax.plot([p0[0], p1[0]], [p0[1], p1[1]], color="0.4", lw=0.4)


def leader(ax, xy, xytext, text, fs=7.5):
    ax.annotate(text, xy=xy, xytext=xytext, fontsize=fs, arrowprops=dict(arrowstyle="-|>", lw=0.6, color="k"),
                ha="left", va="center")


def section_fill(ax, poly, mirror=True, color="0.85"):
    """Draw a revolved part's (r, z) section on both sides of the axis, hatched."""
    for s in ((1, -1) if mirror else (1,)):
        pts = [(s * r, z) for r, z in poly]
        ax.add_patch(MPoly(pts, closed=True, facecolor=color, edgecolor="k", lw=LW, hatch=HATCH))


def centreline(ax, z0, z1):
    ax.plot([0, 0], [z0, z1], color="k", lw=0.5, ls=(0, (12, 3, 2, 3)))


def weld_symbol(ax, xy, xytext, text):
    ax.annotate(text, xy=xy, xytext=xytext, fontsize=7.5, ha="left", va="center",
                arrowprops=dict(arrowstyle="-|>", lw=0.6), bbox=dict(boxstyle="round,pad=0.25", fc="white", ec="k", lw=0.5))


