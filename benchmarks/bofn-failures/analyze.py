"""Tables and paired tests for the failure benchmark (writes tables.md and summary.json).

    python analyze.py

Reads results/<cell>/<scenario>/<strategy>_s<seed>.json. Scores are the best alloy demonstrated
(true objective of the best design carried through every test) as a % of the cell's true optimum
(optima.json). Strategies that ignore failure labels (drop, abandon, partial) give the same run in
`mislabel` as in `mixed` (same failure draws), so their `mixed` runs stand in for them there; the
same holds in `transient` for viab_x and viab_x_partial (= drop) and impute (= viab_node).
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

import numpy as np
from scipy.stats import wilcoxon

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
CELLS = {"al-k1": "al kappa=1 eta=1", "al-k0": "al kappa=0 eta=1", "cu-toy-k1": "cu-toy kappa=1 eta=1", "cu-phys-k1": "cu-phys kappa=1 eta=1",
         "al-k1-full": "al kappa=1 eta=1", "cu-toy-k1-full": "cu-toy kappa=1 eta=1"}
CELL_NAME = {"al-k1": "Aluminum, kappa = 1", "al-k0": "Aluminum, kappa = 0", "cu-toy-k1": "Copper, hand-written truth", "cu-phys-k1": "Copper, physics truth",
             "al-k1-full": "Aluminum, kappa = 1, full-pipeline BOFN", "cu-toy-k1-full": "Copper, hand-written truth, full-pipeline BOFN"}
ORDER = ["nofail", "drop", "abandon", "partial", "keep", "impute", "viab_x", "viab_x_partial", "viab_node", "viab_node_ec"]
LABEL = {"nofail": "no failures (reference)", "drop": "drop (all FAILED)", "abandon": "abandon (all ABANDONED)", "partial": "partial (Ax >= 1.2.4, pending)",
         "keep": "keep partial data, nothing pending", "impute": "impute worst value", "viab_x": "viability on x (Ax 1.3)",
         "viab_x_partial": "viability on x + fit_abandoned", "viab_node": "node-level viability", "viab_node_ec": "node-level viability + failure-priced EI"}
# strategies that ignore labels run identically in `mislabel` and `mixed` (same failure draws); in `transient`,
# viab_x and viab_x_partial reduce to drop, and impute, keep and viab_node coincide
STAND_IN = {"mislabel": {"drop": "mixed", "abandon": "mixed", "partial": "mixed", "keep": "mixed", "nofail": "mixed"},
            "transient": {"viab_x": ("transient", "drop"), "viab_x_partial": ("transient", "drop"), "impute": ("transient", "viab_node"),
                          "keep": ("transient", "viab_node"), "nofail": "mixed"}}
BUDGETS = (25_000, 50_000, 100_000)


def optimum(cell):
    return json.loads((HERE / "optima.json").read_text())[CELLS[cell]]["J_opt"]


def best_at(curve, b):
    v = [c["best"] for c in curve if c["spent"] <= b + 1e-9]
    return v[-1]


def load():
    """runs[cell][scenario][strategy][seed] = result dict (with stand-ins filled in)."""
    runs = defaultdict(lambda: defaultdict(lambda: defaultdict(dict)))
    for p in RES.glob("*/*/*_s*.json"):
        cell, scen = p.parts[-3], p.parts[-2]
        strat, seed = p.stem.rsplit("_s", 1)
        runs[cell][scen][strat][int(seed)] = json.loads(p.read_text())
    for cell in list(runs):
        for scen, rules in STAND_IN.items():
            if scen not in runs[cell]:
                continue
            for strat, src in rules.items():
                if strat in runs[cell][scen]:
                    continue
                s_scen, s_strat = (src, strat) if isinstance(src, str) else src
                if s_strat in runs[cell].get(s_scen, {}):
                    runs[cell][scen][strat] = runs[cell][s_scen][s_strat]
    return runs


def pct(r, cell, b):
    return 100.0 * best_at(r["curve"], b) / optimum(cell)


def boot_ci(d, n=2000, lo=5, hi=95, seed=0):
    rng = np.random.default_rng(seed)
    d = np.asarray(d)
    m = rng.choice(d, size=(n, d.size), replace=True).mean(1)
    return float(np.percentile(m, lo)), float(np.percentile(m, hi))


def holm(ps):
    """Holm-adjusted p-values, same order as ps."""
    idx = np.argsort(ps)
    adj = np.empty(len(ps))
    run = 0.0
    for k, i in enumerate(idx):
        run = max(run, (len(ps) - k) * ps[i])
        adj[i] = min(1.0, run)
    return adj.tolist()


def paired(a, b):
    """a - b on common seeds: mean, CI, wins/ties/losses, Wilcoxon p."""
    seeds = sorted(set(a) & set(b))
    d = np.array([a[s] - b[s] for s in seeds])
    w = int((d > 1e-9).sum())
    t = int((np.abs(d) <= 1e-9).sum())
    l_ = int((d < -1e-9).sum())
    p = float(wilcoxon(d).pvalue) if np.any(np.abs(d) > 1e-9) else 1.0
    lo, hi = boot_ci(d)
    return dict(n=len(seeds), mean=float(d.mean()), ci=(lo, hi), wins=w, ties=t, losses=l_, p=p)


def fmt_p(p):
    return f"{p:.2g}" if p >= 1e-3 else f"{p:.1e}"


def main():
    runs = load()
    summary = {}
    lines = ["# bofn-failures: tables", "", "Generated by `analyze.py` from `results/`. Scores are the best alloy demonstrated, % of the cell's true optimum (mean ± SE over seeds).", ""]
    for cell in CELLS:
        if cell not in runs:
            continue
        for scen in ("mixed", "mislabel", "transient"):
            S = runs[cell].get(scen)
            if not S:
                continue
            strats = [s for s in ORDER if s in S and S[s]]
            lines += [f"## {CELL_NAME[cell]} (`{cell}`), scenario `{scen}`", ""]
            lines += ["| Strategy | n | $25k | $50k | $100k | spend on failed stages | input-caused failures | repeats | transient failures | runs validated |",
                      "|---|---|---|---|---|---|---|---|---|---|"]
            score = {}
            for st in strats:
                R = S[st]
                seeds = sorted(R)
                vals = {b: np.array([pct(R[s], cell, b) for s in seeds]) for b in BUDGETS}
                score[st] = {s: pct(R[s], cell, 100_000) for s in seeds}
                f_spent = np.array([R[s]["spent_on_failed_stages"] for s in seeds]) / 1000
                inp = np.array([R[s]["input_failures"] for s in seeds])
                rep = np.array([R[s]["repeat_input_failures"] for s in seeds])
                tr = np.array([sum(v for k, v in R[s]["failures"].items() if ":transient" in k) for s in seeds])
                val = np.array([R[s]["trials_complete"] for s in seeds])
                se = lambda a: a.std(ddof=1) / np.sqrt(len(a)) if len(a) > 1 else float("nan")
                lines.append(f"| {LABEL[st]} | {len(seeds)} | " + " | ".join(f"{vals[b].mean():.1f} ± {se(vals[b]):.1f}" for b in BUDGETS)
                             + f" | ${f_spent.mean():.1f}k | {inp.mean():.1f} | {rep.mean():.1f} | {tr.mean():.1f} | {val.mean():.1f} |")
                summary.setdefault(cell, {}).setdefault(scen, {})[st] = dict(
                    n=len(seeds), **{f"pct_{b // 1000}k": [float(vals[b].mean()), float(se(vals[b]))] for b in BUDGETS},
                    failed_spend_k=float(f_spent.mean()), input_failures=float(inp.mean()), repeats=float(rep.mean()),
                    transient_failures=float(tr.mean()), validated=float(val.mean()))
            # paired comparisons (pre-registered): viab_node vs every other; partial vs abandon and drop
            comps = [("viab_node", o) for o in strats if o != "viab_node"] + [("partial", "abandon"), ("partial", "drop"), ("keep", "partial"), ("viab_x_partial", "viab_x")]
            comps = [(a, b) for a, b in comps if a in score and b in score]
            res = [paired(score[a], score[b]) for a, b in comps]
            if res:
                adj = holm([r["p"] for r in res])
                lines += ["", "Paired differences at $100k (points of the optimum; matched seeds; Wilcoxon two-sided, Holm-adjusted within this table):", "",
                          "| Comparison | n | mean difference (90% CI) | wins / ties / losses | p | p (Holm) |", "|---|---|---|---|---|---|"]
                for (a, b), r, pa in zip(comps, res, adj):
                    lines.append(f"| {a} − {b} | {r['n']} | {r['mean']:+.1f} ({r['ci'][0]:+.1f} to {r['ci'][1]:+.1f}) | {r['wins']} / {r['ties']} / {r['losses']} | {fmt_p(r['p'])} | {fmt_p(pa)} |")
                    summary[cell][scen].setdefault("paired", {})[f"{a}-{b}"] = dict(r, p_holm=pa)
            lines.append("")
    (HERE / "tables.md").write_text("\n".join(lines) + "\n")
    (HERE / "summary.json").write_text(json.dumps(summary, indent=1) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
