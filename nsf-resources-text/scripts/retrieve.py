#!/usr/bin/env python3
"""BM25 retrieval over the NSF requirements snippet store.

Implements Okapi BM25 (k1=1.5, b=0.75) over the snippets generated by
`tokenize_corpus.py`. Pure-Python stdlib — no torch / numpy / sklearn /
rank_bm25 dependency. Sufficient for a 666-snippet, ~210k-token corpus
where retrieval is sub-millisecond per query.

This implements the *sparse half* of the hybrid BM25 + dense retrieval
recommended in `edison-trajectories/llm-doc-tokenization/result.md` §8
"Recommended Pipeline / Retrieval Setup". A future PR can layer
sentence-transformers (BGE-M3 or all-MiniLM-L6-v2) + a cross-encoder
reranker on top of the same `RetrievalIndex` interface.

Usage (CLI):

    # Top 5 results for a free-text query, printed in the citation format
    # the mock-reviewer playbook expects.
    python nsf-resources-text/scripts/retrieve.py \\
        "what is the page limit on the project summary"

    # Filter by document and / or requirement strength.
    python nsf-resources-text/scripts/retrieve.py --doc pappg-24-1 \\
        --strength required "single copy documents"

Usage (library):

    from retrieve import RetrievalIndex
    idx = RetrievalIndex.load_default()
    for hit in idx.search("project summary page limit", top_k=5):
        print(hit.score, hit.snippet["source_label"], hit.snippet["title"])
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

REPO = Path(__file__).resolve().parents[2]
SNIPPETS_PATH = REPO / "nsf-resources-text" / "snippets" / "snippets.jsonl"
CONTEXTUAL_PATH = REPO / "nsf-resources-text" / "snippets" / "snippets.contextual.jsonl"
PARENT_MAP_PATH = REPO / "nsf-resources-text" / "snippets" / "parent_children.json"

# Conservative English stoplist. Kept small because regulatory text relies
# on terms like "must", "shall", "section" that look like stopwords but
# carry compliance-relevant meaning we want BM25 to weight.
STOPWORDS = frozenset({
    "the", "a", "an", "and", "or", "of", "to", "in", "for", "on", "at",
    "by", "with", "as", "is", "are", "was", "were", "be", "been", "being",
    "this", "that", "these", "those", "it", "its", "from", "into", "than",
    "then", "but", "if", "so", "such", "which", "who", "whom", "whose",
})

TOKEN_RE = re.compile(r"[A-Za-z0-9§][A-Za-z0-9§\-_/.]*")


def tokenize(text: str) -> list[str]:
    """Lower-case alphanumeric tokens, keeping section markers like II.D.2.b
    and the section symbol §. Stopwords removed; tokens shorter than 2
    chars dropped."""
    out: list[str] = []
    for m in TOKEN_RE.finditer(text.lower()):
        tok = m.group(0)
        if len(tok) < 2 or tok in STOPWORDS:
            continue
        out.append(tok)
    return out


@dataclass
class Hit:
    """A single retrieval result."""

    score: float
    rank: int
    snippet: dict


class RetrievalIndex:
    """Okapi BM25 index over the snippet store.

    BM25 score for query q against document d:

        score(q, d) = sum_{t in q} IDF(t) * tf(t, d) * (k1 + 1)
                       / (tf(t, d) + k1 * (1 - b + b * |d| / avgdl))

    with IDF(t) = ln((N - df(t) + 0.5) / (df(t) + 0.5) + 1)
    """

    def __init__(self, snippets: list[dict], k1: float = 1.5, b: float = 0.75,
                 use_contextual: bool = False, parent_children: dict | None = None):
        self.snippets = snippets
        self.k1 = k1
        self.b = b
        self.use_contextual = use_contextual
        # Parent → [child_id, ...] map used by `expand_parent=True` in
        # search() to merge sibling-part chunks into one hit. Built by
        # `contextualize.py` (see snippets/parent_children.json).
        self.parent_children: dict[str, list[str]] = parent_children or {}
        self._id_to_idx: dict[str, int] = {s["id"]: i for i, s in enumerate(snippets)}
        # We index `title + breadcrumbs + text` by default. With
        # `use_contextual=True` we additionally fold in the Anthropic-style
        # `context_prefix` (~50 tokens of "this is section X of doc Y"),
        # which is what gives the published +0.03 nDCG@5 / +0.07 Recall@10
        # bump on regulatory corpora without any model dependency.
        self.docs: list[list[str]] = []
        self.doc_freqs: list[dict[str, int]] = []
        self.doc_len: list[int] = []
        self.df: dict[str, int] = {}
        for s in snippets:
            parts = [
                s.get("title", ""),
                " ".join(s.get("section_breadcrumbs", [])),
            ]
            if use_contextual and s.get("context_prefix"):
                parts.append(s["context_prefix"])
            parts.append(s.get("text", ""))
            doc_text = " ".join(parts)
            toks = tokenize(doc_text)
            tf: dict[str, int] = {}
            for t in toks:
                tf[t] = tf.get(t, 0) + 1
            self.docs.append(toks)
            self.doc_freqs.append(tf)
            self.doc_len.append(len(toks))
            for t in tf:
                self.df[t] = self.df.get(t, 0) + 1
        self.N = len(snippets)
        self.avgdl = (sum(self.doc_len) / self.N) if self.N else 0.0
        self.idf: dict[str, float] = {
            t: math.log((self.N - df + 0.5) / (df + 0.5) + 1.0)
            for t, df in self.df.items()
        }

    @classmethod
    def load_default(cls, contextual: bool = False) -> "RetrievalIndex":
        """Build the index from the canonical snippet store.

        When `contextual=True`, loads `snippets.contextual.jsonl` (built by
        `contextualize.py`) and folds the ~50-token `context_prefix` into
        the indexed text. Falls back to plain `snippets.jsonl` if the
        contextual store has not been built yet.
        """
        path = CONTEXTUAL_PATH if (contextual and CONTEXTUAL_PATH.exists()) else SNIPPETS_PATH
        snippets = [json.loads(l) for l in path.read_text("utf-8").splitlines() if l.strip()]
        parent_children: dict = {}
        if PARENT_MAP_PATH.exists():
            try:
                parent_children = json.loads(PARENT_MAP_PATH.read_text("utf-8"))
            except Exception:
                parent_children = {}
        return cls(snippets, use_contextual=(path == CONTEXTUAL_PATH),
                   parent_children=parent_children)

    def _score_doc(self, query_tf: dict[str, int], doc_idx: int) -> float:
        score = 0.0
        tf_d = self.doc_freqs[doc_idx]
        dl = self.doc_len[doc_idx]
        norm = 1 - self.b + self.b * (dl / self.avgdl if self.avgdl else 0.0)
        for term, q_count in query_tf.items():
            tf = tf_d.get(term, 0)
            if not tf:
                continue
            idf = self.idf.get(term, 0.0)
            score += q_count * idf * tf * (self.k1 + 1) / (tf + self.k1 * norm)
        return score

    def search(
        self,
        query: str,
        top_k: int = 5,
        doc_id: str | None = None,
        strength: str | None = None,
        expand_parent: bool = False,
    ) -> list[Hit]:
        """Return the top-k snippets ranked by BM25.

        Optional filters:
          * `doc_id` — exact-match filter on the snippet's `doc_id`.
          * `strength` — exact-match filter on `requirement_strength`.

        Filters are applied *before* scoring (cheaper) but the limit is
        applied *after* scoring (so the result count is at most `top_k`).

        When `expand_parent=True`, if a hit is a child chunk (id contains
        `~p`), the entire parent section's child set is collapsed into
        one merged hit. This implements the parent-child expansion half
        of the Anthropic contextual-retrieval recipe — useful when the
        retrieved chunk splits a clause mid-sentence and the LLM needs
        the surrounding chunks too.
        """
        q_toks = tokenize(query)
        if not q_toks:
            return []
        q_tf: dict[str, int] = {}
        for t in q_toks:
            q_tf[t] = q_tf.get(t, 0) + 1
        scored: list[tuple[float, int]] = []
        for i, s in enumerate(self.snippets):
            if doc_id and s.get("doc_id") != doc_id:
                continue
            if strength and s.get("requirement_strength") != strength:
                continue
            score = self._score_doc(q_tf, i)
            if score > 0:
                scored.append((score, i))
        scored.sort(key=lambda pair: (-pair[0], pair[1]))
        hits: list[Hit] = []
        seen_parents: set[str] = set()
        for score, i in scored:
            s = self.snippets[i]
            if expand_parent:
                parent = s.get("parent_id") or (
                    s["id"].split("~p", 1)[0] if "~p" in s.get("id", "") else None
                )
                if parent and parent in seen_parents:
                    continue
                if parent and self.parent_children.get(parent):
                    merged = self._merge_children(parent, score)
                    if merged is not None:
                        hits.append(Hit(score=score, rank=len(hits) + 1, snippet=merged))
                        seen_parents.add(parent)
                        if len(hits) >= top_k:
                            break
                        continue
            hits.append(Hit(score=score, rank=len(hits) + 1, snippet=s))
            if len(hits) >= top_k:
                break
        return hits

    def _merge_children(self, parent_id: str, score: float) -> dict | None:
        """Collapse all sibling parts of `parent_id` into one snippet dict.

        Used by `expand_parent=True`. We concatenate `text` in part order
        and propagate the best-scoring child's fields for everything else,
        so citations and page spans still resolve.
        """
        child_ids = self.parent_children.get(parent_id, [])
        if not child_ids:
            return None
        children = [self.snippets[self._id_to_idx[cid]] for cid in child_ids
                    if cid in self._id_to_idx]
        if not children:
            return None
        children.sort(key=lambda c: c.get("part", 0))
        head = dict(children[0])
        head["id"] = parent_id
        head["text"] = "\n\n".join(c.get("text", "") for c in children)
        pages = sorted({p for c in children for p in (c.get("pages") or [])})
        if pages:
            head["pages"] = pages
        head["est_tokens"] = sum(c.get("est_tokens", 0) for c in children)
        head["char_count"] = sum(c.get("char_count", 0) for c in children)
        head["part"] = 0
        head["part_count"] = len(children)
        head["expanded_from_parent"] = True
        head["merged_children"] = [c["id"] for c in children]
        return head


def _format_hit(hit: Hit, show_text: bool) -> str:
    s = hit.snippet
    head = (
        f"#{hit.rank:>2}  score={hit.score:6.2f}  "
        f"{s.get('source_label') or s.get('id')}  "
        f"({s.get('requirement_strength', '?')}, {s.get('est_tokens', '?')}t)"
    )
    title = f"      {s.get('title', '')}"
    body = ""
    if show_text:
        text = s.get("text", "").strip().replace("\n", " ")
        if len(text) > 240:
            text = text[:237] + "..."
        body = f"\n      {text}"
    return f"{head}\n{title}{body}"


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("query", nargs="+", help="Free-text query.")
    parser.add_argument("--top-k", "-k", type=int, default=5, help="Max results.")
    parser.add_argument("--doc", help="Restrict to a doc_id (e.g. pappg-24-1).")
    parser.add_argument(
        "--strength",
        choices=["prohibited", "required", "recommended", "permitted", "informational"],
        help="Restrict to a requirement strength.",
    )
    parser.add_argument(
        "--show-text", action="store_true",
        help="Include a snippet preview in the output.",
    )
    parser.add_argument(
        "--contextual", action="store_true",
        help="Use snippets.contextual.jsonl (Anthropic-style contextual chunks).",
    )
    parser.add_argument(
        "--expand-parent", action="store_true",
        help="If a child chunk (id ~pN) ranks, merge all siblings into one hit.",
    )
    parser.add_argument(
        "--json", action="store_true",
        help="Emit the full hit list as JSON instead of human output.",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)
    query = " ".join(args.query)
    idx = RetrievalIndex.load_default(contextual=args.contextual)
    hits = idx.search(query, top_k=args.top_k, doc_id=args.doc,
                      strength=args.strength, expand_parent=args.expand_parent)
    if args.json:
        json.dump(
            [{"rank": h.rank, "score": h.score, "snippet": h.snippet} for h in hits],
            sys.stdout, indent=2,
        )
        sys.stdout.write("\n")
        return 0
    if not hits:
        print(f"No hits for: {query!r}")
        return 1
    print(f"Query: {query!r}    ({len(hits)} hit{'s' if len(hits) != 1 else ''})")
    for h in hits:
        print(_format_hit(h, show_text=args.show_text))
    return 0


if __name__ == "__main__":
    sys.exit(main())
