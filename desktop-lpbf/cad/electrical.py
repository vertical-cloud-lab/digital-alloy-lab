"""Separate model of the electrical enclosures proposed in electrical.md, checked against the parts of cad/lpbf_low.py they sit
next to. It does not import or change the main model (it rebuilds only the rack frame, the tray rim and the back duct from
the same numbers, lpbf_low.py lines "2. Rack module" and "13. Dock and umbilicals").

  PB1  power box, 16 x 12 x 6 in (406 H x 305 W x 152 D mm) NEMA 12, standing on the tray left of the rack, door to -x,
       disconnect handle on its front (-y) side wall
  DR4  the 4U control drawer (483 x 177.8 mm front, ~400 mm body) at the top of a 12U rack (560 mm, was 11U / 515 mm)

Checks: exact boolean intersection volume and minimum distance (OpenCascade BRepExtrema) of PB1 against the rack frame and
side panels, the tray rim, the umbilical duct and the operator panel; the 12U rack's height against the machine (564 mm,
581.2 mm on its levelling mounts) and the VLM bays (695 mm Modula bay S, 727.5 mm Kardex).

Run: /tmp/capmem 1.0 /tmp/venv/bin/python desktop-lpbf/cad/electrical.py -> desktop-lpbf/analysis/out/electrical/enclosures.md
"""
import json
from pathlib import Path

import cadquery as cq
from OCP.BRepExtrema import BRepExtrema_DistShapeShape

OUT = Path(__file__).resolve().parents[1] / "analysis" / "out" / "electrical"
Z_TRAY = -212.0                     # lpbf_low.py: -160 - (foot body + stem)
TRAY_INNER = (2426.0, 840.0)
U = 44.45


def box(x0, x1, y0, y1, z0, z1):
    return cq.Solid.makeBox(x1 - x0, y1 - y0, z1 - z0, cq.Vector(x0, y0, z0))


def rack(n_u):
    rx0, rx1, ry0, ry1 = -990.0, -430.0, -300.0, 300.0
    h = 25.0 + n_u * U + 1.6
    rz0, rz1 = Z_TRAY, Z_TRAY + h
    posts = []
    for x in (rx0, rx1 - 25):
        for y in (ry0, ry1 - 25):
            posts.append(box(x, x + 25, y, y + 25, rz0 + 20, rz1 - 20))
    for z in (rz0, rz1 - 20):
        posts += [box(rx0, rx1, ry0, ry0 + 25, z, z + 20), box(rx0, rx1, ry1 - 25, ry1, z, z + 20),
                  box(rx0, rx0 + 25, ry0 + 25, ry1 - 25, z, z + 20), box(rx1 - 25, rx1, ry0 + 25, ry1 - 25, z, z + 20)]
    panels = [box(rx0 - 2, rx0, ry0, ry1, rz0 + 20, rz1), box(rx1, rx1 + 2, ry0, ry1, rz0 + 20, rz1)]
    return cq.Compound.makeCompound(posts + panels), h


def main():
    parts = {}
    frame, h12 = rack(12)
    parts["rack frame + side panels (12U)"] = frame
    ix, iy = TRAY_INNER[0] / 2, TRAY_INNER[1] / 2
    parts["tray rim (inside face)"] = cq.Compound.makeCompound([box(-ix - 12, -ix, -iy - 12, iy + 12, Z_TRAY, Z_TRAY + 20),
                                                                box(-ix, ix, -iy - 12, -iy, Z_TRAY, Z_TRAY + 20),
                                                                box(-ix, ix, iy, iy + 12, Z_TRAY, Z_TRAY + 20)])
    dx0 = TRAY_INNER[0] / 2 - 110
    parts["umbilical duct (back edge)"] = box(-980.0, dx0, 320.0, 380.0, Z_TRAY, Z_TRAY + 50)
    parts["operator panel box"] = box(-470.0, -420.0, -332.0, -300.0, Z_TRAY + 140, Z_TRAY + 440)
    # PB1 on 15 mm feet, 16 mm clear of the rack's left side panel
    pb1 = box(-1008.0 - 152.4, -1008.0, -300.0, -300.0 + 304.8, Z_TRAY + 15, Z_TRAY + 15 + 406.4)
    handle = box(-1110.0, -1060.0, -300.0 - 45.0, -300.0, Z_TRAY + 250, Z_TRAY + 330)   # Socomec S00 handle envelope on the front side wall
    pb1c = cq.Compound.makeCompound([pb1, handle])
    rows = []
    for name, shp in parts.items():
        inter = pb1c.intersect(shp)
        vol = inter.Volume() if inter is not None else 0.0
        d = BRepExtrema_DistShapeShape(pb1c.wrapped, shp.wrapped)
        d.Perform()
        rows.append(dict(part=name, intersection_mm3=round(vol, 3), min_distance_mm=round(d.Value(), 2)))
    res = dict(pb1_box_mm=[152.4, 304.8, 406.4], pb1_top_above_tray_mm=15 + 406.4, rack_12U_height_mm=round(h12, 1),
               rack_11U_height_mm=515.0, machine_height_mm=564.0, machine_on_mounts_mm=581.2, bays_mm={"Modula bay S": 695.0, "Kardex": 727.5},
               drawer_4U=dict(front_mm=[483.0, 177.8], z_mm=[round(Z_TRAY + 25 + 8 * U, 1), round(Z_TRAY + 25 + 12 * U, 1)]),
               checks=rows)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "enclosures.json").write_text(json.dumps(res, indent=1))
    L = ["# Electrical enclosures against the model", "", "Generated by [`cad/electrical.py`](../../../cad/electrical.py): a separate model, the main model files are not changed.", "",
         f"- PB1: 152 x 305 x 406 mm (6 x 12 x 16 in) on 15 mm feet, top {15 + 406.4:.0f} mm above the tray, left of the rack (x −1160 to −1008).",
         f"- Rack with the 4U drawer: 12U, {h12:.0f} mm tall (was 515); the machine is 564 mm (581.2 mm on its mounts); bays 695 mm (Modula S) and 727.5 mm (Kardex).",
         f"- The 4U drawer sits at z {Z_TRAY + 25 + 8 * U:.0f} to {Z_TRAY + 25 + 12 * U:.0f} mm.", "",
         "| PB1 (with its handle) against | Intersection (mm³) | Minimum distance (mm) |", "|---|---|---|"]
    for r in rows:
        L.append(f"| {r['part']} | {r['intersection_mm3']} | {r['min_distance_mm']} |")
    L += ["", "Not checked: the fibre loop over the rack (it rises 45 mm with the 12U rack), the MiR's approach to the tray's left end, and anything the main model may add later at x < −990."]
    (OUT / "enclosures.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
