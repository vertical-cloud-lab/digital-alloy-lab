#!/usr/bin/env python3
"""Plume emission lines against the candidate filter bands (issue #260, monitoring/optics.md §2.3).

Reads NIST Atomic Spectra Database line lists (Kramida, Ralchenko, Reader and NIST ASD Team, NIST ASD v5.12,
https://physics.nist.gov/asd) for Al I, Mg I, Na I, K I, Si I, Zn I, Ca I, Li I and Ar I between 500 and 1800 nm, saved as CSV by
    curl "https://physics.nist.gov/cgi-bin/ASD/lines1.pl?spectra=Al+I&low_w=500&upp_w=1800&unit=1&format=2&A_out=0&..."
(fetched 2026-11-25T06:44Z; the CSVs stay in /tmp, their sha256 are in monitoring/optics.md). For each band it lists the lines
inside it, weighted for an optically thin plume in local thermodynamic equilibrium: I ~ g_k A_ki exp(-E_k / kT) / lambda,
relative to the strongest line of the same element, at 3000 K (a weakly ionised Al vapour plume; Edison r8-melt-plume quotes a
~3360 K model plume) and 5000 K (a hot-plume bound). Concentrations differ by element (Na, K and Li are trace impurities), so
compare lines within an element, and treat any band containing a resonance line (Na D, K 766/770) as unusable.

    python lines.py [NIST_CSV_DIR]       (default /tmp/optB/nist)
Writes analysis/out/monitoring/optics/lines.json and lines.md.
"""
from __future__ import annotations

import csv
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = ROOT / "analysis" / "out" / "monitoring" / "optics"
OUT.mkdir(parents=True, exist_ok=True)
K_CM = 0.6950348   # Boltzmann constant in cm^-1 per K

# candidate bands (centre, FWHM, nm): camera, two-colour pair, InGaAs
BANDS = {"650/40": (650, 40), "650/10": (650, 10), "700/40": (700, 40), "700/10": (700, 10), "750/40": (750, 40),
         "800/40": (800, 40), "850/40": (850, 40), "850/10": (850, 10), "900/40": (900, 40), "940/10": (940, 10),
         "950/25": (950, 25), "1300/12": (1300, 12), "1550/12": (1550, 12), "1600/12": (1600, 12), "1650/12": (1650, 12)}
ELEMENTS = ("Al_I", "Mg_I", "Si_I", "Zn_I", "Ca_I", "Na_I", "K_I", "Li_I", "Ar_I")


def num(s):
    s = (s or "").replace('="', "").replace('"', "").strip().strip("[]()+*?")
    try:
        return float(s)
    except ValueError:
        return None


def load(dirpath):
    lines = []
    for el in ELEMENTS:
        f = Path(dirpath) / f"{el}.csv"
        if not f.exists():
            continue
        rows = list(csv.reader(f.read_text().splitlines()))
        hdr = rows[0]
        ix = {h: i for i, h in enumerate(hdr)}
        for r in rows[1:]:
            if len(r) < len(hdr) - 1:
                continue
            lam = num(r[ix["obs_wl_air(nm)"]]) or num(r[ix["ritz_wl_air(nm)"]])
            A = num(r[ix["Aki(s^-1)"]])
            Ek = num(r[ix["Ek(cm-1)"]])
            Jk = r[ix["J_k"]].replace('="', "").replace('"', "").strip()
            try:
                gk = 2 * eval(Jk, {"__builtins__": {}}) + 1 if Jk else None   # J like "3/2"
            except Exception:  # noqa: BLE001
                gk = None
            if lam is None or Ek is None:
                continue
            lines.append(dict(el=el.replace("_", " "), lam=lam, A=A, Ek=Ek, gk=gk, intens=num(r[ix["intens"]])))
    return lines


def weight(l, T):
    if not l["A"] or not l["gk"]:
        return None
    return l["gk"] * l["A"] * math.exp(-l["Ek"] / (K_CM * T)) / l["lam"]


def main(dirpath="/tmp/optB/nist"):
    lines = load(dirpath)
    R = dict(source="NIST ASD lines, 500-1800 nm, fetched 2026-11-25T06:44Z", bands={})
    best = {}
    for T in (3000.0, 5000.0):
        for el in {l["el"] for l in lines}:
            w = [weight(l, T) for l in lines if l["el"] == el and weight(l, T)]
            best[(el, T)] = max(w) if w else None
    for b, (c, fw) in BANDS.items():
        lo, hi = c - fw / 2 - 2, c + fw / 2 + 2           # 2 nm margin for filter edges and angle shift
        inside = []
        for l in lines:
            if lo <= l["lam"] <= hi:
                rec = dict(el=l["el"], nm=round(l["lam"], 2), A=l["A"], Ek_cm=l["Ek"])
                for T in (3000.0, 5000.0):
                    w = weight(l, T)
                    rec[f"rel_{int(T)}K"] = (w / best[(l["el"], T)]) if (w and best[(l["el"], T)]) else None
                inside.append(rec)
        inside.sort(key=lambda r: -(r["rel_3000K"] or 0))
        strong = [r for r in inside if (r["rel_3000K"] or 0) > 1e-2 or (r["rel_5000K"] or 0) > 5e-2]
        R["bands"][b] = dict(range_nm=[lo, hi], n_lines=len(inside), strong=strong[:12], verdict="clean" if not strong else
                             "lines: " + ", ".join(f"{r['el']} {r['nm']}" for r in strong[:6]))
    (OUT / "lines.json").write_text(json.dumps(R, indent=1) + "\n")
    L = ["# Plume lines inside the candidate bands (generated by analysis/monitoring/optics/lines.py)", "",
         "Lines from NIST ASD (500-1800 nm). 'Strong' = within 1 % of its element's strongest line in this range at 3000 K, or 5 % at "
         "5000 K, for an optically thin LTE plume (I ~ g A exp(-E/kT)/lambda). Bands include a 2 nm margin.", "",
         "| band (nm) | lines inside | strong lines (element, nm, relative weight at 3000 K / 5000 K) |", "|---|---:|---|"]
    for b, v in R["bands"].items():
        s = "; ".join(f"{r['el']} {r['nm']} ({(r['rel_3000K'] or 0):.2g} / {(r['rel_5000K'] or 0):.2g})" for r in v["strong"][:6]) or "none"
        L.append(f"| {b} | {v['n_lines']} | {s} |")
    (OUT / "lines.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    return R


if __name__ == "__main__":
    main(*(sys.argv[1:2] or []))
