"""Mass, centre of mass and VLM-tray load of the low-profile model (cad/lpbf_low.py).

Mass of each part = CAD volume x density of its material (lpbf_low.MAT), unless the part carries a catalogue or
estimated mass (vendor units: laser, pump, blower, UPS, motors). Also checks the static tip-over margin of each
module: the horizontal acceleration that would tip it, a_tip = g * (shortest CoM-to-foot-line distance) / CoM height.

Run:  python desktop-lpbf/analysis/mass_budget.py     -> analysis/out/mass.json, analysis/out/mass.md
"""
from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "cad"))
import lpbf_low as M  # noqa: E402

FOOT = {"rack": (-990.0, -430.0, -300.0, 300.0), "process": (-370.0, 290.0, -265.0, 215.0), "gas": (400.0, 990.0, -250.0, 300.0)}
TRAY_LOAD = {"Kardex Shuttle XP 500, 2450 mm tray (strong tray)": 490.0, "Modula MC50D": 500.0}


def compute():
    parts = M.build()
    rows, mods = [], {}
    for p in parts:
        if "context" in p.tags:
            continue
        vol = p.shape.Volume() * 1e-9          # m3
        c = p.shape.Center()
        if p.mass_kg is not None:
            m, basis = p.mass_kg, "catalogue/estimate"
        else:
            m, basis = vol * M.MAT[p.mat]["rho"], f"{M.MAT[p.mat]['label']} x volume"
        rows.append(dict(part=p.name, module=p.module, material=M.MAT[p.mat]["label"], mass_kg=round(m, 3), basis=basis, com=(c.x, c.y, c.z)))
        d = mods.setdefault(p.module, dict(mass_kg=0.0, mx=0.0, my=0.0, mz=0.0))
        d["mass_kg"] += m
        d["mx"] += m * c.x
        d["my"] += m * c.y
        d["mz"] += m * c.z
    out = {}
    for k, d in mods.items():
        m = d["mass_kg"]
        com = (d["mx"] / m, d["my"] / m, d["mz"] / m) if m else (0, 0, 0)
        e = dict(mass_kg=round(m, 1), com_mm=[round(v, 1) for v in com])
        if k in FOOT:
            x0, x1, y0, y1 = FOOT[k]
            fx0, fx1, fy0, fy1 = x0 + 30, x1 - 30, y0 + 30, y1 - 30      # foot centres
            h = com[2] - M.Z_TRAY
            arm = min(com[0] - fx0, fx1 - com[0], com[1] - fy0, fy1 - com[1])
            e.update(foot=FOOT[k], com_height_above_tray_mm=round(h, 1), min_lever_mm=round(arm, 1), tip_accel_g=round(arm / h, 2))
        out[k] = e
    total = sum(v["mass_kg"] for v in out.values())
    by_mat = {}
    for r in rows:
        by_mat[r["material"]] = by_mat.get(r["material"], 0.0) + r["mass_kg"]
    return dict(modules=out, total_kg=round(total, 1), tray_limits_kg=TRAY_LOAD, by_material={k: round(v, 1) for k, v in sorted(by_mat.items(), key=lambda kv: -kv[1])},
                parts=sorted(rows, key=lambda r: -r["mass_kg"]))


def main():
    r = compute()
    out = HERE / "out"
    out.mkdir(exist_ok=True)
    (out / "mass.json").write_text(json.dumps(r, indent=1))
    L = ["# Mass budget", "", f"Total on the tray: **{r['total_kg']} kg**, against tray ratings of " +
         ", ".join(f"{v:g} kg ({k})" for k, v in r["tray_limits_kg"].items()) + ". Generated by `analysis/mass_budget.py`.", "",
         "| Module | Mass (kg) | CoM height above tray (mm) | Shortest lever to a foot line (mm) | Tips at (g) |", "|---|---|---|---|---|"]
    for k, v in r["modules"].items():
        L.append(f"| {k} | {v['mass_kg']} | {v.get('com_height_above_tray_mm', '')} | {v.get('min_lever_mm', '')} | {v.get('tip_accel_g', '')} |")
    L += ["", "| Material | Mass (kg) |", "|---|---|"] + [f"| {k} | {v} |" for k, v in r["by_material"].items()]
    L += ["", "Heaviest parts:", "", "| Part | Module | Material | Mass (kg) | Basis |", "|---|---|---|---|---|"]
    for x in r["parts"][:20]:
        L.append(f"| {x['part']} | {x['module']} | {x['material']} | {x['mass_kg']} | {x['basis']} |")
    (out / "mass.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:12]))


if __name__ == "__main__":
    main()
