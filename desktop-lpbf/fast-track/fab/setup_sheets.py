"""Setup sheets for every posted mill setup (#260, PR 294 round 3; the CAM review's fix 6, review-r3.md section 7).

One block per setup: the program, which face is up, how the piece is held, the stock, where G54 sits against a
corner the operator can touch off, the tools in order with their stick-out and flute length, and the run time.
From out/cam.json (setups, ops, the stock box in each setup's frame), /tmp/ft-fab/pieces.json (holding, stock;
written by parts.py) and tools.py.

G54: the programs' origin is the piece's model origin, rotated into the setup's frame. The sheet gives it from the
stock box's top front-left corner (min x, min y, top z in the setup's frame): set G54 at that corner, then shift it by
(dx, dy, dz). On a first setup the corner is the sawn blank's; on a flip, touch off on the faces the earlier setup
left (faced top, the vise's fixed jaw against a machined side) and check the shift against the drawing. Not checked
by a machinist; prove each program out on the control's graphics first.

    /tmp/venv/bin/python desktop-lpbf/fast-track/fab/setup_sheets.py   -> out/setup-sheets.md
"""
from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import tools as T  # noqa: E402

OUT = HERE / "out"


def main():
    cam = json.loads((OUT / "cam.json").read_text())
    spec = json.loads((pathlib.Path("/tmp/ft-fab") / "pieces.json").read_text())
    pcs = {p["pid"]: p for p in spec["pieces"]}
    L = ["# Setup sheets, CAD v2 (round 3)", "",
         "Generated by [`../setup_sheets.py`](../setup_sheets.py) from `cam.json`, the pieces' spec and `tools.py`. "
         "One block per posted mill setup, in program order. G54 is given from the stock box's top front-left corner "
         "in the setup's frame (min x, min y, top z): set G54 there, then shift it by (dx, dy, dz). Stick-out is "
         "from the holder's nose. Times are the programs' recount (feeds as programmed, rapids at 25.4 m/min) and "
         "exclude loading and touch-off. Not checked by a machinist: prove each program out on the control's "
         "graphics first.", ""]
    n = 0
    for s in cam["setups"]:
        pc = pcs.get(s["pid"], {})
        su = next((x for x in pc.get("setups", []) if x["name"] == s["setup"]), {})
        x0, y0, z0, sl, sw, sh = s["stock_box_setup"]
        tools_used = []
        for m in s["ops"]:
            if m["tool"] not in tools_used:
                tools_used.append(m["tool"])
        L.append("## %s: %s (%s up)" % (s["setup"], pc.get("name", ""), s["up"]))
        L.append("")
        L.append("- **Program:** [`%s`](../%s), %d operations, %d tool changes, %.1f min%s" % (
            s["gcode"], s["gcode"], len(s["ops"]), s["tool_changes"], s["total_min"],
            (" (run %d times, indexed)" % s.get("repeat", 1)) if s.get("repeat", 1) > 1 else ""))
        L.append("- **Setup:** %s" % (s.get("label") or su.get("label", "")))
        L.append("- **Holding:** %s" % (su.get("hold") or "vise (not stated)"))
        L.append("- **Stock:** %s; material %s; the box in this setup's frame is %.1f x %.1f x %.1f mm" % (
            pc.get("stock", ""), pc.get("material", ""), sl, sw, sh))
        L.append("- **G54:** from the stock's top front-left corner, dx %+.3f, dy %+.3f, dz %+.3f mm (the corner is at "
                 "X %.3f Y %.3f Z %.3f in program coordinates)" % (-x0, -y0, -(z0 + sh), x0, y0, z0 + sh))
        L.append("- **Tools, in order:**")
        for t in tools_used:
            v = T.TOOLS[t]
            L.append("  - T%d %s: Ø%.3f mm, stick-out %.0f mm%s, %d rpm" % (
                t, v["name"], v["d"], v["length"], (", flutes %.1f mm" % v["edge"]) if v.get("edge") else "",
                v["rpm"]))
        L.append("- **Operations:** " + "; ".join("%s (T%d)" % (m["label"], m["tool"]) for m in s["ops"]))
        L.append("")
        n += 1
    (OUT / "setup-sheets.md").write_text("\n".join(L) + "\n")
    print("wrote %d setup sheets to %s" % (n, OUT / "setup-sheets.md"))


if __name__ == "__main__":
    main()
