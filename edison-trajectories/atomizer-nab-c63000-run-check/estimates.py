"""Back-of-envelope numbers for the #219 atomizer run with the alloy actually used, 630 bronze (UNS C63000).

    python estimates.py > estimates.md

Order-of-magnitude only; every input is printed next to its result. Sources: C63000 limits and melting
range from Concast's data sheet (https://www.concast.com/c63000.php); the W-in-Cu-Ni fit from Eremenko,
Minakova & Churakov 1977 (doi:10.1007/BF00806131) as used in ../atomizer-cu30ni-w-plate/ (branch
claude/issue-219-20261027-2129); rePOWDER Cu-alloy settings from doi:10.3390/ma19132803 (CuSn8) and
doi:10.3390/ma17143396 (NAB). Standard-state data are rounded handbook values, good to ~10-20 kJ/mol.
"""

import math

R = 8.314  # J/(mol K)
T = 1573.15  # K, the 1300 C setpoint
RT = R * T
M = {"Cu": 63.546, "Al": 26.982, "Ni": 58.693, "Fe": 55.845, "W": 183.84}
NAB_WT = {"Cu": 82.0, "Al": 10.0, "Ni": 5.0, "Fe": 3.0}  # nominal C63000, wt%


def section(title):
    print(f"\n## {title}\n")


print("# Back-of-envelope estimates: 630 bronze (C63000) on the rePOWDER\n")
print("Generated by `estimates.py`. Order-of-magnitude only; every input is shown.")

section("1. Superheat at the 1300 C setpoint")
for name, liquidus in (("C63000 (630 bronze, NAB)", 1054), ("Cu-30Ni (what #219 assumed)", 1240)):
    print(f"- {name}: liquidus {liquidus} C, so **{1300 - liquidus} C** of superheat at 1300 C.")

section("2. Melt composition in atom fractions")
n = {k: v / M[k] for k, v in NAB_WT.items()}
x = {k: v / sum(n.values()) for k, v in n.items()}
print("Nominal Cu-10Al-5Ni-3Fe (wt%): " + ", ".join(f"x_{k} = {v:.3f}" for k, v in x.items()) + ".")

section("3. Tungsten solubility: C63000 against Cu-30Ni")
fit = lambda z: 10 ** (-7.011 + 7.770 * math.sqrt(z))  # Eremenko 1977, 1300 C, z = Ni/(Ni+Cu) atomic
for name, wt_ni in (("C63000", 5.0), ("Cu-30Ni", 30.0)):
    if name == "C63000":
        z = n["Ni"] / (n["Ni"] + n["Cu"])
    else:
        z = (30 / M["Ni"]) / (30 / M["Ni"] + 70 / M["Cu"])
    xw = fit(z)
    m_solvent = z * M["Ni"] + (1 - z) * M["Cu"]
    wt = 100 * xw * M["W"] / (xw * M["W"] + (1 - xw) * m_solvent)
    print(f"- {name}: z = Ni/(Ni+Cu) = {z:.3f}, x_W = {xw:.2e}, about **{wt:.2g} wt% W** "
          f"({wt * 1e4:.0f} ppm by mass) at saturation.")
print("\nThe fit was measured for z = 0.054-0.368, so C63000 (z = 0.062) is inside it. It covers Cu-Ni only:"
      " the 3% Fe (Fe dissolves W) and the 10% Al (Al-W intermetallics) would raise the C63000 value, but"
      " not plausibly by the factor of ~300 between the two alloys. The W-based coating in AMAZEMET's 2026"
      " plate study is a Si-W infiltration layer of W5Si3 + WC rather than metallic W"
      " (doi:10.3390/ma19132803); if our plate is that kind, this bounds dissolution of metallic W only.")

section("4. Does the Al in the melt attack graphite, BN or silica at 1300 C?")
print("Threshold Al activity for each reaction, from Delta G at 1573 K (liquid Al reference):\n")
# 4 Al(l) + 3 C = Al4C3: dH = -208.8 - 4*10.71 kJ, dS = 88.95 - 4*(28.3 + 11.47) - 3*5.74 J/K
dg_al4c3 = (-208.8 - 4 * 10.71) * 1e3 - T * (88.95 - 4 * (28.3 + 11.47) - 3 * 5.74)
a_al4c3 = math.exp(dg_al4c3 / (4 * RT))
# Al(l) + BN = AlN + B: dH = -318.0 + 252.0 - 10.71 kJ, dS = 20.2 + 5.9 - (28.3 + 11.47) - 14.8 J/K
dg_aln = (-318.0 + 252.0 - 10.71) * 1e3 - T * (20.2 + 5.9 - (28.3 + 11.47) - 14.8)
a_aln = math.exp(dg_aln / RT)
print(f"- 4 Al + 3 C -> Al4C3: Delta G = {dg_al4c3 / 1e3:.0f} kJ/mol, so it needs **a_Al > {a_al4c3:.2f}**.")
print(f"- Al + BN -> AlN + B (pure B): Delta G = {dg_aln / 1e3:.0f} kJ/mol, so it needs "
      f"**a_Al > {a_aln:.2f}**. If the boron dissolves at a_B ~ 0.01, the threshold drops to "
      f"~{a_aln * 0.01:.4f}, so a thin AlN/boride reaction film and a little B pickup are possible.")
# 4/3 Al(l) + SiO2 = 2/3 Al2O3 + Si, from Ellingham lines per mol O2 at 1573 K
dg_al2o3 = -1120.5e3 + 214.0 * T
dg_sio2 = -907.1e3 + 175.0 * T
dg_si = dg_al2o3 - dg_sio2
print(f"- 4/3 Al + SiO2 -> 2/3 Al2O3 + Si: Delta G = {dg_si / 1e3:.0f} kJ per mol SiO2, so it runs at any "
      "plausible a_Al: silica in a binder or on the plate coating ends up as dissolved Si.\n")
print("Estimated a_Al in the melt: liquid Cu-Al mixes very exothermically (integral enthalpy minimum "
      "about -18 to -20 kJ/mol near x_Al = 0.35-0.4). As a regular solution, Omega = -75 kJ/mol; with "
      "G_excess between 0.6 and 1.0 of H_excess,")
for frac in (1.0, 0.6):
    rt_ln_g = frac * -75e3 * (1 - x["Al"]) ** 2
    g = math.exp(rt_ln_g / RT)
    print(f"- G_ex/H_ex = {frac}: gamma_Al = {g:.3f}, **a_Al = {g * x['Al']:.3f}**")
print("\nNi and Fe bind Al further (NiAl, FeAl), so a_Al ~ 0.005-0.02 is 4-20x below the Al4C3 and "
      "AlN thresholds: the graphite crucible, the BN coat and rod, and the carbon-fiber plate should not "
      "form Al4C3 or bulk AlN, whereas silica and B2O3 binders will be reduced.")

section("5. Pour pressure against the capillary threshold of a 0.5 mm non-wetting bore")
r = 0.25e-3  # m
cos_t = math.cos(math.radians(140))  # metal on hBN or graphite, non-wetting
for name, gamma in (("C63000 melt", 1.2), ("Al alloy melt", 0.87)):
    print(f"- {name}: surface tension {gamma} N/m, contact angle 140 deg, so a melt column needs "
          f"**{2 * gamma * abs(cos_t) / r / 1e5 * 1000:.0f} mbar** to enter the bore.")
rho = 6900.0  # kg/m3, liquid NAB near 1300 C (7.58 g/cm3 solid)
vol = 1.080 / rho
for d in (0.05, 0.06):
    h = vol / (math.pi * d ** 2 / 4)
    print(f"- Metallostatic head of 1.08 kg in a {d * 1000:.0f} mm bore crucible: {h * 100:.1f} cm, "
          f"{rho * 9.81 * h / 100:.0f} mbar at the start, falling to zero.")
p_cap = 2 * 1.2 * abs(cos_t) / r
area = math.pi * r ** 2
print("\nMass flow through the bore (discharge coefficient 0.8, ignoring head):\n")
for label, dp in (("0.19 bar graining against a 0.1 bar chamber (if both absolute)", 0.09e5),
                  ("0.4 bar: AMAZEMET's CuSn8 protocol, 0.6 bar working against a 0.2 bar backfill", 0.4e5),
                  ("1.4 bar: turbo held (1.5 bar against 0.1 bar)", 1.4e5)):
    net = dp - p_cap
    q = 0.8 * area * math.sqrt(2 * rho * net) * 1e3 if net > 0 else 0.0
    t = 1080 / q / 60 if q else float("inf")
    print(f"- {label}: net {net / 1e5 * 1000:.0f} mbar, **{q:.1f} g/s**, 1.08 kg in {t:.1f} min.")

section("6. Expected particle size (Lang's capillary-wave relation)")
for f in (20e3, 40e3):
    d50 = 0.34 * (8 * math.pi * 1.2 / (rho * f ** 2)) ** (1 / 3)
    print(f"- {f / 1e3:.0f} kHz: d50 = {d50 * 1e6:.0f} um.")
print("\nThe published NAB run at 40 kHz and 1.5 bar measured d10/d50/d90 = 48/98/174 um after a 200 um "
      "sieve (doi:10.3390/ma17143396), about twice Lang's value, as expected when the melt arrives faster "
      "than a thin film can atomize it.")
