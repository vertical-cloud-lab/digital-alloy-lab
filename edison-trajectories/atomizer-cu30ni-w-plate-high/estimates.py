"""Back-of-envelope numbers for a W- versus Mo-coated carbon-fiber plate under a Cu-30Ni melt (issue #219).

    python estimates.py > estimates.md

Everything here is an order-of-magnitude estimate with the inputs printed next to the result. The one
measured anchor is Mo: 3.7 wt% Mo dissolves in a Cu-32Ni melt at 1300 C (Teodorovich, Churakov &
Kostenetskaya 1980, doi:10.1007/bf00791375). The matching W measurement (Eremenko, Minakova & Churakov
1977, doi:10.1007/BF00806131) is paywalled, so the W solubility below is a bracket, not a value.
"""

import math

R = 8.314  # J/(mol K)
M = {"Cu": 63.546, "Ni": 58.693, "W": 183.84, "Mo": 95.95}
RHO = {"W": 19.3, "Mo": 10.2, "CC": 1.7, "melt": 7.9}  # g/cm3; CC = carbon-carbon composite
FUSION = {"W": (3695.0, 52.3e3), "Mo": (2896.0, 37.5e3)}  # (melting point K, enthalpy of fusion J/mol)
# Elastic modulus (GPa), Poisson ratio and mean CTE (1/K) from room temperature to ~1000-1300 C.
ELASTIC = {"W": (411.0, 0.28, 4.9e-6), "Mo": (329.0, 0.31, 5.6e-6)}
CC_INPLANE = (70.0, 0.0e-6, 1.5e-6)  # C/C in-plane modulus (GPa) and CTE range (1/K)


def mole_fraction_ni(wt_ni):
    n_ni, n_cu = wt_ni / M["Ni"], (100 - wt_ni) / M["Cu"]
    return n_ni / (n_ni + n_cu)


def mean_solvent_mass(wt_ni):
    x = mole_fraction_ni(wt_ni)
    return x * M["Ni"] + (1 - x) * M["Cu"]


def ideal_x(metal, T):
    """Ideal solubility (mole fraction) of a solid metal in a liquid, from its own fusion data."""
    tm, dh = FUSION[metal]
    return math.exp(-dh * (1 - T / tm) / (R * T))


def wt_to_x(wt, metal, wt_ni):
    n = wt / M[metal]
    return n / (n + (100 - wt) / mean_solvent_mass(wt_ni))


def x_to_wt(x, metal, wt_ni):
    m = x * M[metal]
    return 100 * m / (m + (1 - x) * mean_solvent_mass(wt_ni))


def fmt(v):
    return f"{v:.1f}" if v < 10 else f"{v:.0f}"


def section(title):
    print(f"\n## {title}\n")


print("# Back-of-envelope estimates: W- vs Mo-coated carbon-fiber plate under Cu-30Ni\n")
print("Generated by `estimates.py`. Order-of-magnitude only; every input is shown.")

section("1. Solubility of W in liquid Cu-30Ni (bracket) against the measured Mo value")
T = 1573.0
x_ni = mole_fraction_ni(30)
print(f"Cu-30Ni (wt%) has x_Ni = {x_ni:.3f}. At 1300 C the ideal solubility (solid -> liquid, no "
      f"interactions) is x = {ideal_x('W', T):.3f} for W and x = {ideal_x('Mo', T):.3f} for Mo, because W "
      "melts 800 K higher.\n")
x_mo = wt_to_x(3.7, "Mo", 32)
rtlng_mo = R * T * math.log(ideal_x("Mo", T) / x_mo) / 1e3
print(f"Measured Mo: 3.7 wt% in Cu-32Ni at 1300 C is x = {x_mo:.4f}, an excess term RT ln(gamma) = "
      f"{rtlng_mo:.0f} kJ/mol against liquid Mo.\n")
print("For W, anchor on that measurement: W melts 800 K higher (ideal solubility 0.37x Mo's), and its excess "
      "term in Cu-Ni is taken as 0-15 kJ/mol less favourable than Mo's (Cu repels W at least as much as Mo; "
      "Ni attracts W less: the Ni-W liquid at the 1495 C invariant holds 20.7 at% W, the Ni-Mo eutectic "
      "liquid 35 at% Mo):\n")
print("| W excess vs Mo (kJ/mol) | x_W | W solubility (wt%) | x_W / x_Mo |")
print("|---|---|---|---|")
for extra in (0, 5, 10, 15):
    x_w = ideal_x("W", T) / math.exp((rtlng_mo + extra) * 1e3 / (R * T))
    print(f"| +{extra} | {x_w:.4f} | {x_to_wt(x_w, 'W', 30):.2f} | {x_w / x_mo:.2f} |")
print("\nSo W solubility is about **0.8-2.6 wt%** (Edison's interpolation: 1-2 wt%). W and Mo have nearly the "
      "same molar volume (9.55 vs 9.38 cm3/mol), so the mole-fraction ratio sets the recession ratio: a "
      "dense W coat should recede roughly **3-8x more slowly** than a Mo coat, not orders of magnitude.\n")
print("Not used: a regular-solution extrapolation from W's near-zero solubility in pure liquid Cu (<=1e-3 %, "
      "Naidich 1977 via Edison) predicts ~0.03 wt% W. The same construction, if Mo is similarly insoluble in "
      "pure Cu, predicts ~0.1 wt% Mo where 3.7 wt% is measured, so it badly underestimates refractory-metal "
      "solubility in Cu-Ni.")

section("2. How fast the melt eats a dense coat (mass-transfer-limited dissolution)")
print("Recession rate r = k * rho_melt * w_sat / rho_coat. k = D/delta with D ~ 2e-9 m2/s (W in liquid Ni is "
      "2.4e-9 m2/s at 1480-1750 C) and a boundary layer delta of 10-70 um under a thin, ultrasonically "
      "agitated film gives k ~ 3e-5 to 1.5e-4 m/s. Under the falling stream (jet ~1.5 m/s, 2 mm, "
      "Sc ~ 250) a stagnation-point correlation gives k ~ 5e-4 m/s.\n")
cases = [("Mo", 3.7), ("W", 2.6), ("W", 1.2), ("W", 0.8)]
ks = [("film, low", 3e-5), ("film, high", 1.5e-4), ("under the stream", 5e-4)]
print("| Coat | Solubility (wt%) | " + " | ".join(f"r, {n} (um/min)" for n, _ in ks) + " |")
print("|---|---|" + "---|" * len(ks))
for metal, w in cases:
    rates = [k * RHO["melt"] * 1e3 * (w / 100) / (RHO[metal] * 1e3) * 1e6 * 60 for _, k in ks]
    print(f"| {metal} | {w} | " + " | ".join(f"{r:.0f}" if r >= 10 else f"{r:.1f}" for r in rates) + " |")
print("\nMinutes to cut through a dense coat of a given thickness, using the film-zone range (the spot "
      "under the stream goes 3-15x faster):\n")
print("| Coat | Solubility (wt%) | 25 um | 100 um | 250 um |")
print("|---|---|---|---|---|")
for metal, w in cases:
    lo, hi = [k * RHO["melt"] * (w / 100) / RHO[metal] * 1e6 * 60 for k in (3e-5, 1.5e-4)]
    cells = [f"{fmt(t_um / hi)}-{fmt(t_um / lo)}" for t_um in (25, 100, 250)]
    print(f"| {metal} | {w} | " + " | ".join(cells) + " |")
print("\nSanity check against the one measurement: a solid Mo sonotrode with ~10 cm2 wetted for 20 min at "
      "the film-zone Mo rate loses "
      f"{10 * 0.0052 * 20 * RHO['Mo']:.0f}-{10 * 0.0258 * 20 * RHO['Mo']:.0f} g, i.e. "
      f"{100 * 10 * 0.0052 * 20 * RHO['Mo'] / 1100:.0f}-{100 * 10 * 0.0258 * 20 * RHO['Mo'] / 1100:.0f} wt% of a 1.1 kg "
      "charge, bracketing the ~2.6 wt% Mo that Goncharov 2026 found in powder from a Mo sonotrode.")

section("3. Thermal-mismatch stress in the coat on cooling (dense coat, in-plane C/C)")
print("sigma = E * (alpha_coat - alpha_CC) * dT / (1 - nu), C/C in-plane CTE 0-1.5e-6/K, coat stress-free at "
      "the temperature it was made or last relaxed:\n")
print("| Coat | Stress-free at | Stress at room temperature (GPa, tensile) |")
print("|---|---|---|")
for metal in ("Mo", "W"):
    e, nu, a = ELASTIC[metal]
    for t0 in (700, 1300):
        lo = e * (a - CC_INPLANE[2]) * (t0 - 25) / (1 - nu)
        hi = e * (a - CC_INPLANE[1]) * (t0 - 25) / (1 - nu)
        print(f"| {metal} | {t0} C | {lo:.1f}-{hi:.1f} |")
print("\nBoth are well above what a W or Mo film can carry without cracking or yielding (roughly "
      "0.3-1 GPa), so a dense coat on in-plane C/C cracks (mud-cracking) or debonds on cooling. W is no better than Mo "
      "here, and W is brittle below a few hundred C while Mo keeps some ductility near room "
      "temperature.")

section("4. Added mass and flexural stiffness of a coated plate")
print("Same coating thickness on both faces of a dense coat; C/C core E = 70 GPa, rho = 1.7 g/cm3. "
      "'Flexural f' is the change in a bending-mode frequency, sqrt(D/m), relative to the bare plate:\n")
print("| Plate (mm) | Coat per side (um) | Mass, Mo coat | Mass, W coat | Flexural f, Mo | Flexural f, W | W vs Mo |")
print("|---|---|---|---|---|---|---|")
for h_mm in (2.0, 3.0):
    h = h_mm * 1e-3
    d0 = CC_INPLANE[0] * 1e9 * h ** 3 / 12
    m0 = RHO["CC"] * 1e3 * h
    for t_um in (25, 100, 250):
        t = t_um * 1e-6
        res = {}
        for metal in ("Mo", "W"):
            e = ELASTIC[metal][0] * 1e9
            d = d0 + 2 * e * (t ** 3 / 12 + t * ((h + t) / 2) ** 2)
            m = m0 + 2 * RHO[metal] * 1e3 * t
            res[metal] = (m / m0, math.sqrt((d / m) / (d0 / m0)))
        print(f"| {h_mm:.0f} | {t_um} | +{100 * (res['Mo'][0] - 1):.0f}% | +{100 * (res['W'][0] - 1):.0f}% | "
              f"+{100 * (res['Mo'][1] - 1):.0f}% | +{100 * (res['W'][1] - 1):.0f}% | "
              f"{100 * (res['W'][1] / res['Mo'][1] - 1):+.1f}% |")
print("\nFor scale, 3D Lab's sonotrode patent (EP3766610) says the system tolerates only +/-5% detuning and "
      "that heating by the melt alone lowers the resonance 3-9%. If the plate is only a tip mass on a "
      "much heavier horn the shift is far smaller, so the generator's frequency reading with the new "
      "plate fitted is what settles it.")

section("5. Capillary infiltration of a porous dip coat")
print("Washburn: t = 2 * eta * L^2 / (gamma * r * cos(theta)), eta = 4.5 mPa s, gamma = 1.3 N/m, L = 100 um:\n")
print("| Pore radius (um) | Contact angle | Time to cross 100 um |")
print("|---|---|---|")
for r_um in (0.5, 5):
    for theta in (10, 60):
        t = 2 * 4.5e-3 * (100e-6) ** 2 / (1.3 * r_um * 1e-6 * math.cos(math.radians(theta)))
        print(f"| {r_um} | {theta} deg | {t * 1e3:.2f} ms |")
print("\nCu-Ni wets clean W and Mo (Cu infiltration of porous W is how W-Cu composites are made), so a "
      "porous slurry coat of either metal is soaked through in milliseconds and puts the melt on the "
      "carbon. Only a dense coat can act as a barrier.")
