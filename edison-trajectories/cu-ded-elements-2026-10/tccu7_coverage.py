"""CALPHAD coverage of the 50 queried elements in Thermo-Calc's TCCU7.

The aluminum palette was screened by how many Al-X-Y ternaries TCAl10 assesses
(../edison-search-space-reframing.md). This does the same for copper with
TCCU7 (TCS Cu-based Alloys Database, "Technical Information", available from
Thermo-Calc 2026b, document created 12 Jun 2026:
https://thermocalc.com/wp-content/uploads/Documentation/Databases/Thermodynamic/tccu7-technical-info.pdf).
It lists 34 elements, 175 assessed binaries (a matrix on p. 13, transcribed
below) and 79 assessed ternaries (p. 14). Every Cu-X binary is assessed for
the 33 other elements.

Run: python tccu7_coverage.py  (writes tccu7_coverage.md)
"""

import pathlib
from itertools import combinations

from elements import ELEMENTS

TCCU7_ELEMENTS = ("Ag Al Au As B Be Bi C Ca Cd Ce Co Cr Cu Fe Ge La Mg Mn Mo Nb "
                  "Ni O P Pb Pt S Se Si Sn Ta Ti Zn Zr").split()

# p. 13, row element: assessed partners to its left in the matrix
BINARY_ROWS = {
    "Al": "Ag", "As": "", "Au": "Ag", "B": "Al", "Be": "Ag Al", "Bi": "Ag Al",
    "C": "Al", "Ca": "Al", "Cd": "Al", "Ce": "Al", "Co": "Ag Al Be",
    "Cr": "Ag Al Co",
    "Cu": "Ag Al As Au B Be Bi C Ca Cd Ce Co Cr",
    "Fe": "Ag Al C Ce Co Cr Cu", "Ge": "Ag Al Au Co Cr Cu",
    "La": "Ce Cr Cu Fe", "Mg": "Al Ce Cu La", "Mn": "Ag Al Bi Co Cu Fe",
    "Mo": "Cr Cu Fe", "Nb": "Co Cr Cu",
    "Ni": "Ag Al Be Bi Ce Co Cr Cu Fe Ge La Mg Mn Mo Nb",
    "O": "Al Cr Cu Fe Mn", "P": "Ag Al Cr Cu Fe Ni",
    "Pb": "Ag Al Bi Co Cu Fe Mn Ni", "Pt": "Cu", "S": "Cu Fe Mn Ni Pb",
    "Se": "Cu", "Si": "Ag Al Au Be Bi Co Cr Cu Fe Mg Mn Ni O P Pb",
    "Sn": "Ag Al Bi Co Cr Cu Fe Ge Mg Mn Nb Ni P Pb S Si",
    "Ta": "Cr Cu Fe Nb Ni Si", "Ti": "Al Cu Ge Nb Ni Si",
    "Zn": "Ag Al Bi Co Cu Fe Mn Ni P Pb S Si Sn",
    "Zr": "Al B C Cr Cu Fe Ge La Mg Mn Ni O Si Sn Ti",
}
BINARIES = {frozenset((a, b)) for a, row in BINARY_ROWS.items() for b in row.split()}

# p. 14
TERNARIES = [frozenset(t.split("-")) for t in """
Ag-Au-Cu Ag-Cr-Cu Ag-Cu-Ge Ag-Cu-Ni Ag-Cu-P Ag-Cu-Si Ag-Cu-Sn Al-Ce-Cu
Al-Cu-Fe Al-Cu-Mn Al-Cu-Ni Al-Cu-O Al-Cu-Si Al-Cu-Sn Al-Cu-Zn Al-Fe-Ni
Au-Cu-Ge Be-Cu-Ni C-Cu-Fe Ce-Cu-La Ce-Cu-Ni Co-Cr-Cu Co-Cu-Fe Co-Cu-Mn
Co-Cu-Nb Co-Cu-Ni Co-Cu-Si Cr-Cu-Fe Cr-Cu-La Cr-Cu-Mo Cr-Cu-Nb Cr-Cu-Ni
Cr-Cu-Si Cr-Cu-Sn Cr-Cu-Zr Cu-Fe-Mn Cu-Fe-Mo Cu-Fe-Ni Cu-Fe-O Cu-Fe-S
Cu-Fe-Si Cu-Fe-Sn Cu-Fe-Ta Cu-Fe-Zn Cu-La-Ni Cu-La-Zr Cu-Mg-Ni Cu-Mg-Si
Cu-Mg-Sn Cu-Mn-Ni Cu-Mn-O Cu-Mn-S Cu-Mn-Si Cu-Mn-Sn Cu-Mn-Zn Cu-Mo-Ni
Cu-Nb-Ni Cu-Nb-Sn Cu-Nb-Ti Cu-Ni-P Cu-Ni-Pb Cu-Ni-S Cu-Ni-Si Cu-Ni-Sn
Cu-Ni-Ta Cu-Ni-Ti Cu-Ni-Zn Cu-P-Sn Cu-Pb-S Cu-Pb-Sn Cu-Pb-Zn Cu-S-Sn
Cu-S-Zn Cu-Si-Ti Cu-Si-Zn Cu-Sn-Zn Cu-Ti-Zr Fe-Mn-O Ni-Sn-Zn
""".split()]

assert len(BINARIES) == 175, len(BINARIES)
assert len(TERNARIES) == 79, len(TERNARIES)

# The seawater core: elements of 90-10, 70-30, C71640, C72200 and NAB.
CORE = ["Ni", "Al", "Fe", "Mn", "Cr"]


def row(el: str) -> dict:
    if el not in TCCU7_ELEMENTS:
        return {"in_db": False}
    with_cu = [t for t in TERNARIES if {"Cu", el} <= t]
    core_bin = [c for c in CORE if c != el and frozenset((el, c)) in BINARIES]
    core_ter = [c for c in CORE if c != el and frozenset(("Cu", el, c)) in TERNARIES]
    return {"in_db": True, "n_cu_ternaries": len(with_cu),
            "cu_ni_x": frozenset(("Cu", "Ni", el)) in TERNARIES,
            "cu_al_x": frozenset(("Cu", "Al", el)) in TERNARIES,
            "core_binaries": core_bin, "core_ternaries": core_ter}


def tier(r: dict) -> str:
    if not r["in_db"]:
        return "4 (not in TCCU7)"
    n = r["n_cu_ternaries"]
    return "1 (>=6)" if n >= 6 else "2 (3-5)" if n >= 3 else "3 (0-2)"


def main() -> None:
    lines = ["# TCCU7 coverage of the 50 queried elements", "",
             "Generated by `tccu7_coverage.py` from the TCCU7 technical information "
             "(Thermo-Calc, 2026b; 34 elements, 175 assessed binaries, 79 assessed "
             "ternaries). Every Cu-X binary is assessed for the elements in the "
             "database. Tiers follow the aluminum run's TCAl10 tiers, counted here "
             "as assessed Cu-X-Y ternaries. \"Core\" = Ni, Al, Fe, Mn, Cr.", "",
             "| Element | In TCCU7 | Cu-X-Y ternaries | Tier | Cu-Ni-X | Cu-Al-X | "
             "X-core binaries assessed | Cu-X-core ternaries assessed |",
             "| --- | --- | ---: | --- | --- | --- | --- | --- |"]
    order = sorted([e for e in ELEMENTS if e != "Cu"],
                   key=lambda e: (-row(e).get("n_cu_ternaries", -1), e))
    for el in order:
        r = row(el)
        if r["in_db"]:
            ni = "n/a" if el == "Ni" else "yes" if r["cu_ni_x"] else "no"
            al = "n/a" if el == "Al" else "yes" if r["cu_al_x"] else "no"
            lines.append(
                f"| {el} | yes | {r['n_cu_ternaries']} | {tier(r)} | {ni} | {al} | "
                f"{', '.join(r['core_binaries']) or '-'} | "
                f"{', '.join(r['core_ternaries']) or '-'} |")
        else:
            lines.append(f"| {el} | no | - | {tier(r)} | - | - | - | - |")
    # Core coverage: pairs among Cu + core
    lines += ["", "Pairs among the core elements (X-Y binaries and Cu-X-Y ternaries):", ""]
    for a, b in combinations(CORE, 2):
        lines.append(f"- {a}-{b}: binary {'assessed' if frozenset((a, b)) in BINARIES else 'NOT assessed'}; "
                     f"Cu-{a}-{b} ternary {'assessed' if frozenset(('Cu', a, b)) in TERNARIES else 'NOT assessed'}")
    out = pathlib.Path(__file__).with_name("tccu7_coverage.md")
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()


def palette_stats(palette: list) -> dict:
    """Coverage of a candidate palette (Cu as base), as in the aluminum run:
    share of palette pairs whose Cu-X-Y ternary is assessed, and how many
    Cu-X-Y-Z quaternaries have 4, 3, ... of their 4 constituent ternaries
    assessed (Cu-X-Y, Cu-X-Z, Cu-Y-Z, X-Y-Z)."""
    pal = [e for e in palette if e != "Cu"]
    pairs = list(combinations(pal, 2))
    covered = [p for p in pairs if frozenset(("Cu",) + p) in TERNARIES]
    quats = {}
    for x, y, z in combinations(pal, 3):
        n = sum(frozenset(t) in TERNARIES for t in
                (("Cu", x, y), ("Cu", x, z), ("Cu", y, z), (x, y, z)))
        quats[n] = quats.get(n, 0) + 1
    missing = [f"{a}-{b}" for a, b in pairs if frozenset(("Cu", a, b)) not in TERNARIES]
    not_in_db = [e for e in pal if e not in TCCU7_ELEMENTS]
    return {"n": len(pal), "pairs": len(pairs), "pairs_covered": len(covered),
            "quaternaries_by_assessed_ternaries": dict(sorted(quats.items(), reverse=True)),
            "pairs_without_ternary": missing, "not_in_tccu7": not_in_db}
