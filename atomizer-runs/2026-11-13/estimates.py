"""Back-of-envelope numbers for the Nov 13 2026 collection-cup failure (#269).

Run with `python estimates.py > estimates.md`. Every input is listed with its source or marked as an
assumption; treat the outputs as order-of-magnitude checks, not measurements.
"""
import math

print("# Nov 13 2026: estimates\n")
print("Generated by `estimates.py`. Inputs are rounded handbook values or readings from the run videos;")
print("each section says which. Order-of-magnitude checks only.\n")

# ---------------------------------------------------------------- 1. heat in the charge
m = 816.0                      # g, charge (run notes, #219)
T_melt, T_sol, T_liq, T0 = 1300.0, 1040.0, 1054.0, 25.0
cp_s, cp_l, L = 0.48, 0.53, 230.0   # J/g/K, J/g/K, J/g (assumed: Cu-alloy handbook values, +/-15 %)
h_per_g = cp_s * (T_sol - T0) + L + cp_l * (T_melt - T_liq)
print("## 1. Heat carried by the charge\n")
print(f"- Sensible (solid, {T0:.0f}-{T_sol:.0f} C) {cp_s*(T_sol-T0):.0f} J/g + latent {L:.0f} J/g + liquid "
      f"({T_liq:.0f}-{T_melt:.0f} C) {cp_l*(T_melt-T_liq):.0f} J/g = **{h_per_g:.0f} J/g**")
print(f"- For {m:.0f} g: **{m*h_per_g/1e3:.0f} kJ** (about the energy to heat 2 L of water from 20 to 100 C)")
print(f"- Of that, {m*(cp_l*(T_melt-T_liq)+L)/1e3:.0f} kJ has to leave before the metal is fully solid.\n")

# ---------------------------------------------------------------- 2. droplet cooling in flight
print("## 2. How far each droplet size gets towards solid before it reaches the cone\n")
rho, k_ar, eps, sigma = 7000.0, 0.035, 0.3, 5.67e-8   # kg/m3 (liquid NAB), W/m/K (Ar ~800 K), emissivity (assumed)
T_gas = 300.0 + 273.15
fall = 0.8                    # m, plate to cone outlet (assumed, 0.5-1 m)
t_fall = math.sqrt(2 * fall / 9.81)
print(f"Fall of {fall} m from rest takes about **{t_fall:.2f} s** (drag ignored; it only lengthens the flight of")
print("the smallest drops). Heat loss is convection (Ranz-Marshall, Nu = 2 + 0.6 Re^0.5 Pr^0.33, with the")
print("velocity reached halfway down) plus radiation (emissivity 0.3). Energy to remove before fully solid:")
q_solid = (cp_l * (T_melt - T_liq) + L) * 1e3   # J/kg
print(f"{q_solid/1e3:.0f} J/g.\n")
print("| Droplet diameter | Time to solidify | Fall time / time to solidify | Arrives as |")
print("|---|---|---|---|")
mu_ar, rho_ar, pr = 4.0e-5, 0.6, 0.67    # Pa s, kg/m3 (Ar ~800 K, 1 bar), Prandtl
for d in (50e-6, 100e-6, 200e-6, 1e-3, 2e-3, 3e-3):
    v = min(9.81 * t_fall / 2, 3.0)
    re = rho_ar * v * d / mu_ar
    nu = 2 + 0.6 * re ** 0.5 * pr ** 0.33
    h_c = nu * k_ar / d
    T_s = (T_melt + T_sol) / 2 + 273.15
    h_r = eps * sigma * (T_s ** 4 - T_gas ** 4) / (T_s - T_gas)
    h = h_c + h_r
    t_sol = rho * q_solid * d / (6 * h * (T_s - T_gas))
    frac = t_fall / t_sol
    state = "solid, then cools further" if frac >= 1 else ("mostly liquid" if frac < 0.5 else "partly liquid")
    size = f"{d*1e6:.0f} um" if d < 1e-3 else f"{d*1e3:.0f} mm"
    print(f"| {size} | {t_sol:.3g} s | {frac:.2g} | {state} |")
print("\nFine powder (d50 around 100 um on the good runs) freezes within the first few centimetres and reaches")
print("the cup cool. Shot of 1-3 mm, which is what the plate threw on Nov 13, reaches the cone still largely")
print("liquid, sticks to whatever it lands on and keeps nearly all of its heat.\n")

# ---------------------------------------------------------------- 3. contact temperatures
print("## 3. Surface temperature the moment hot bronze touches each material\n")
print("Two semi-infinite bodies in contact settle at T_c = (e1 T1 + e2 T2)/(e1 + e2), with effusivity")
print("e = sqrt(k rho c). Bronze at 1000 C (just solid) against parts at 25 C:\n")
mats = {  # k W/m/K, rho kg/m3, c J/kg/K (handbook values, rounded)
    "NAB bronze (solid)": (40, 7600, 450),
    "316 stainless (flange)": (16, 8000, 500),
    "Borosilicate 3.3 glass": (1.1, 2230, 750),
    "Silicone rubber seal": (0.2, 1200, 1300),
    "FKM (Viton) seal": (0.2, 1850, 1400),
    "EPDM seal": (0.25, 1150, 1800),
}
e = {n: math.sqrt(k * r * c) for n, (k, r, c) in mats.items()}
eb = e["NAB bronze (solid)"]
print("| Bronze at 1000 C touching | Contact temperature |")
print("|---|---|")
for n in list(mats)[1:]:
    tc = (eb * 1000 + e[n] * 25) / (eb + e[n])
    print(f"| {n} | {tc:.0f} C |")
print("\nEPDM seals are rated to about 150 C continuous, silicone to about 200-230 C and FKM to about 200-250 C,")
print("so a seal that a bead touches is overheated at once; it only survives if no hot metal reaches it.")
print("AMAZEMET recalls the seal that burned as EPDM (WhatsApp, Nov 17), the lowest-rated of the three.\n")

# ---------------------------------------------------------------- 4. thermal shock of the glass
print("## 4. Thermal-shock margin of the glass\n")
print("Stress from a sudden surface temperature change: sigma = E alpha dT / (1 - nu). Taking 40 MPa as the")
print("tensile stress an abraded glass surface fails at (assumed; design values are lower):\n")
print("| Glass | E (GPa) | alpha (1/K) | dT that reaches 40 MPa |")
print("|---|---|---|---|")
for n, E, a, nu in (("Soda-lime", 70e9, 9.0e-6, 0.22), ("Borosilicate 3.3", 64e9, 3.3e-6, 0.20),
                    ("Fused quartz", 72e9, 0.55e-6, 0.17)):
    print(f"| {n} | {E/1e9:.0f} | {a:.2g} | {40e6*(1-nu)/(E*a):.0f} K |")
tc_glass = (eb * 1000 + e["Borosilicate 3.3 glass"] * 25) / (eb + e["Borosilicate 3.3 glass"])
print(f"\nBronze at 1000 C puts the touched glass surface near {tc_glass:.0f} C: about 6x what borosilicate takes,")
print("and close to the limit even for fused quartz.\n")

# ---------------------------------------------------------------- 5. barometric pressure and the gauge
print("## 5. The vacuum gauge reads relative to the room, and the room pressure changes\n")
print("Surface pressure at Provo (Open-Meteo archive, ERA5, grid elevation 1427 m), mid-afternoon on each run day.")
print("If the pump reaches the same absolute pressure every time, the gauge can only read (that pressure minus")
print("the room's). Taking -850 mbar as the reading on a day of average room pressure (the five NAB run days):\n")
baro = {"Oct 27": 856.2, "Oct 28": 859.2, "Nov 5": 860.6, "Nov 10": 867.1, "Nov 13": 849.2, "Nov 17": 848.4}
mean_runs = sum(baro[d] for d in ("Oct 27", "Oct 28", "Nov 5", "Nov 10", "Nov 13")) / 5
p_abs = mean_runs - 850.0
print("| Day | Room (hPa = mbar) | Gauge at the same absolute vacuum |")
print("|---|---|---|")
for dday, p in baro.items():
    print(f"| {dday} | {p:.0f} | {p_abs - p:.0f} mbar |")
print(f"\nNov 13's room pressure was {baro['Oct 27']-baro['Nov 13']:.0f}-{baro['Nov 10']-baro['Nov 13']:.0f} mbar lower than on the other NAB run days,")
print("so the same pump-down reads that much less negative.")
print("The video of the Nov 13 pump-down at 500 C reads -834 mbar at its lowest (Gage's notes: about -830).")
print("Weather accounts for most of the shortfall from the usual -850. What is left, 0-10 mbar depending on which")
print("day is the reference, is within the scatter of the reading, and is also about the size of leak that")
print("section 6 says would leave ~1000 ppm O2. The gauge can't tell those two apart.\n")

# ---------------------------------------------------------------- 6. oxygen after a backfill
print("## 6. What it takes to leave about 900 ppm O2 after a backfill\n")
p_fill = 849.2 + 150        # mbar absolute after backfill to +150 mbar
print(f"Backfilling with argon to +150 mbar gauge is about {p_fill:.0f} mbar absolute. The O2 left equals the O2")
print("partial pressure at the bottom of the pump-down divided by that:\n")
print("| Air left at the bottom of the pump-down | O2 after backfill |")
print("|---|---|")
for pair in (0.1, 0.5, 1.0, 2.0, 4.0, 5.0):
    print(f"| {pair:.1f} mbar | {0.209*pair/p_fill*1e6:.0f} ppm |")
print("\nNormal runs (low 20s ppm) leave about 0.1 mbar of air. The 873-1000 ppm on Nov 13 needs about 4 mbar of")
print("air at the bottom of every pump-down, while the gauge reading barely changes.\n")
p_low, cyc = 16.0, 1
print("A one-off dose of air (such as the chamber drawing in air when the machine lost power) is purged quickly:")
for n in range(1, 4):
    print(f"- after {n} pump-down/backfill cycle(s) to {p_low:.0f} mbar absolute: {209000*(p_low/p_fill)**n:.1f} ppm")
print("\nSix extra purges should therefore have brought a one-off dose of air below 1 ppm. A reading that went")
print("back to 1000 ppm after every purge means one of three things: a source that refills the chamber during")
print("each pump-down (a leak open to the room), a sensor fault, or a sensor that isn't being flushed. AMAZEMET")
print("says chamber gas only flows through the sensor above +50 mbar, so the sensor sits without flow during")
print("every pump-down, and it needs a small flow at overpressure to clear (WhatsApp, Nov 14 and Nov 18). With")
print("too little flow, the reading could stay near the top of the scale after every purge, whatever the")
print("chamber held. These numbers describe the chamber only if the sensor was seeing chamber gas.\n")
# pump-down curve read off video 3 (nRPmLzQUUBY), room ~850 mbar
pts = [(12, -270), (15, -441), (18, -544), (21, -625), (24, -682), (27, -726), (30, -760), (33, -783), (36, -801)]
p0 = 849.2
xs = [t for t, _ in pts]
ys = [math.log(p0 + g - 14.0) for _, g in pts]   # subtract an assumed base of ~14 mbar absolute
n = len(xs); mx = sum(xs) / n; my = sum(ys) / n
slope = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
tau = -1 / slope
print(f"The pump-down filmed in video 3 (t = 12-36 s) gives a chamber time constant V/S of about **{tau:.0f} s**.")
print("Valve the pump off at full vacuum and watch the gauge (a rate-of-rise test). A leak that leaves 4 mbar of")
print(f"air at the bottom of a pump-down raises the pressure by about 4/{tau:.0f} = {4/tau:.2f} mbar/s, roughly")
print(f"**{4/tau*60:.0f} mbar per minute**, while a tight chamber with ~0.1 mbar of air rises about "
      f"{0.1/tau*60:.1f} mbar/min plus outgassing.")
print("A 5-minute rate-of-rise test therefore separates the two cases by more than the gauge's resolution.")

# ---------------------------------------------------------------- 7. heat from the oxygen in the chamber
print("\n## 7. Could the oxygen have added heat?\n")
print("Gage asked AMAZEMET whether a leak letting oxygen in could have added to the heat in the cup; the reply")
print("was \"Can't confirm that the oxygen could matter here\" (WhatsApp, Nov 17). The upper bound: let every O2")
print("molecule in the chamber gas react with the melt. During the melt and the pour the chamber is at")
print("overpressure, so a leak lets gas out rather than in, and the argon topping it up carries only a few ppm O2.")
print("The chamber's volume isn't recorded here, so take 50-300 L (assumed).\n")
R, T_gas_k = 8.314, 300.0
p_pa = p_fill * 100.0                       # about 999 mbar absolute, from section 6
x_o2 = 1000e-6                              # the top of the sensor's scale
dH = {"4/3 Al + O2 -> 2/3 Al2O3": 1675.7 / 1.5, "4 Cu + O2 -> 2 Cu2O": 2 * 168.6}  # kJ per mol O2 (handbook)
q_charge = m * h_per_g / 1e3                # kJ, section 1
print("| Chamber gas volume | O2 at 1000 ppm | Heat if it all oxidizes Al | Heat if it all oxidizes Cu | Share of the charge's heat |")
print("|---|---|---|---|---|")
for v_l in (50, 100, 300):
    n_o2 = x_o2 * p_pa * v_l / 1000 / (R * T_gas_k)
    q_al = n_o2 * dH["4/3 Al + O2 -> 2/3 Al2O3"]
    q_cu = n_o2 * dH["4 Cu + O2 -> 2 Cu2O"]
    print(f"| {v_l} L | {n_o2*1e3:.1f} mmol | {q_al:.1f} kJ | {q_cu:.1f} kJ | {q_al/q_charge*100:.1f} % at most |")
print(f"\nEven at the top of the scale and with the largest volume, oxidation releases about 2 % of the {q_charge:.0f} kJ")
print("the charge carries. The oxygen did not heat the cup. If it mattered, it did so indirectly: an Al2O3 skin")
print("on a melt with 10 % Al works against atomization, and more shot means more hot metal reaching the cup.")
