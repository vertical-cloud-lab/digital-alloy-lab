"""Shortened, instrumented copy of PhaseForgePlus example/pt-w.py (Pt-W tuning).

Same PhaseForgePlus(...) call and the same scipy CG call as upstream optimize(), but the run is
capped by --maxiter and a wall-clock --budget, every objective evaluation is logged, and the best
parameter vector is written to a TDB (upstream optimize() returns an OptimizeResult and never
writes a TDB). Also checks whether the NEQ ("MLIP regularizer") blocks generated by PhaseForgePlus
are actually used by ESPEI's FixedConfigurationPropertyResidual, and why not.
"""
import argparse
import copy
import json
import time
from pathlib import Path

import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("--data", required=True, help="PhaseForgePlus example/data directory")
ap.add_argument("--out", required=True, help="results directory (data/ subdir is used)")
ap.add_argument("--maxiter", type=int, default=5)
ap.add_argument("--budget", type=float, default=600.0, help="optimizer wall-clock budget, s")
ap.add_argument("--prefix", default="PhaseForgePlus-PtW")
args = ap.parse_args()

t0 = time.time()
from espei.core_utils import get_prop_data  # noqa: E402
from espei.error_functions.non_equilibrium_thermochemical_error import (  # noqa: E402
    FixedConfigurationPropertyResidual,
    filter_sublattice_configurations,
)
from espei.utils import MemoryStorage, PickleableTinyDB, database_symbols_to_fit  # noqa: E402
from scipy import optimize as scipy_optimize  # noqa: E402
from tinydb import where  # noqa: E402

from phaseforgeplus import PhaseForgePlus  # noqa: E402
from phaseforgeplus.utils.objective import objective_function  # noqa: E402

summary = {"import_s": round(time.time() - t0, 2)}
data = Path(args.data)
out = Path(args.out) / "data"
out.mkdir(parents=True, exist_ok=True)

t = time.time()
pfp = PhaseForgePlus(
    db=str(data / "pt-w.tdb"),
    zpf_path=str(data),
    points=[1801, 1601, 1401, 1201, 1001, 802, 602, 402, 202],
    pressure=101325,
    temperature=298.15,
)
summary["constructor_s"] = round(time.time() - t, 2)
syms = database_symbols_to_fit(pfp.db)
x0 = np.asarray(pfp.get_initial_values(), dtype=float)
summary["n_params"] = len(syms)
summary["zpf_datasets"] = len(pfp.db_zpf)
# ESPEI's gradient branch pops the fitted VV symbols out of the Database it is given
# (zpf_error.py:153, non_equilibrium_thermochemical_error.py:286), so pfp.db is mutated by the first
# objective evaluation. copy.deepcopy() does not isolate it: pycalphad 0.11.2 Database.__deepcopy__
# copies only _parameters and shares .symbols by reference. Side checks and TDB writing therefore
# use fresh Database() loads of the same file.
from pycalphad import Database  # noqa: E402

tdb_path = str(data / "pt-w.tdb")
db_start = Database(tdb_path)

# --- does ESPEI use the NEQ blocks that PhaseForgePlus generated? ---
first = pfp.db_neq.all()[0] if len(pfp.db_neq) else {}
summary["neq_blocks_generated"] = len(pfp.db_neq)
summary["neq_block_phases_field"] = repr(first.get("phases"))
summary["neq_block_solver_keys"] = sorted(first.get("solver", {}).keys())
neq = FixedConfigurationPropertyResidual(Database(tdb_path), pfp.db_neq, phase_models=None, symbols_to_fit=syms)
summary["neq_blocks_used_by_espei"] = len(neq.thermochemical_data)
ln, gn = neq.get_likelihood(x0)
summary["neq_loglik_x0"] = float(ln)
summary["neq_grad_norm_x0"] = float(np.linalg.norm(gn))
# root cause: ESPEI's query is where('phases') == [phase]; PhaseForgePlus writes a bare string
comps = sorted(db_start.elements)
q = where("solver").exists()
summary["espei_query_hits_as_generated"] = {
    ph: len(get_prop_data(comps, ph, "HM_MIX", pfp.db_neq, additional_query=q)) for ph in pfp.phases}
fixed_db = PickleableTinyDB(storage=MemoryStorage)
for b in pfp.db_neq.all():
    b = dict(b)
    b["phases"] = [b["phases"]]
    fixed_db.insert(b)
summary["espei_query_hits_with_phases_as_list"] = {
    ph: len(get_prop_data(comps, ph, "HM_MIX", fixed_db, additional_query=q)) for ph in pfp.phases}
try:
    filter_sublattice_configurations(get_prop_data(comps, pfp.phases[0], "HM_MIX", fixed_db, additional_query=q),
                                     [["PT", "W"]])
    summary["next_failure_after_phases_fix"] = None
except Exception as e:  # expected: KeyError from the 'sublattice_configuraations' typo
    summary["next_failure_after_phases_fix"] = f"{type(e).__name__}: {e}"
print(json.dumps(summary, indent=1), flush=True)

# --- upstream objective (rebuilds both residuals on every call), CG as in optimize() ---
func = objective_function(pfp.db, pfp.db_zpf, pfp.db_neq)
trace = []
best = {"f": np.inf, "x": x0.copy()}


class BudgetExceeded(Exception):
    pass


t_opt0 = time.time()


def wrapped(x):
    t1 = time.time()
    f, g = func(x)
    rec = {"eval": len(trace), "f": float(f), "grad_norm": float(np.linalg.norm(g)),
           "eval_s": round(time.time() - t1, 2), "elapsed_s": round(time.time() - t_opt0, 1),
           "max_abs_dx": float(np.max(np.abs(np.asarray(x) - x0)))}
    trace.append(rec)
    print(json.dumps(rec), flush=True)
    if np.isfinite(f) and f < best["f"]:
        best["f"] = float(f)
        best["x"] = np.array(x, dtype=float)
    if time.time() - t_opt0 > args.budget:
        raise BudgetExceeded
    return f, g


status = "finished"
try:
    res = scipy_optimize.minimize(wrapped, x0, jac=True, method="CG",
                                  options={"disp": True, "maxiter": args.maxiter})
    summary["scipy_message"] = str(res.message)
    summary["scipy_nit"] = int(res.nit)
    summary["scipy_success"] = bool(res.success)
except BudgetExceeded:
    status = f"stopped by wall-clock budget ({args.budget:.0f} s)"
summary["optimizer_status"] = status
summary["optimizer_s"] = round(time.time() - t_opt0, 1)
summary["n_evals"] = len(trace)
summary["objective_x0"] = trace[0]["f"] if trace else None
summary["objective_best"] = best["f"]
summary["pfp_db_symbols_to_fit_after_run"] = len(database_symbols_to_fit(pfp.db))
summary["pfp_get_initial_values_len_after_run"] = len(pfp.get_initial_values())
summary["db_start_symbols_to_fit_after_run"] = len(database_symbols_to_fit(db_start))
summary["params"] = {s: {"x0": float(a), "best": float(b)} for s, a, b in zip(syms, x0, best["x"])}

# --- write the tuned TDB (start TDB is the upstream example/data/pt-w.tdb) ---
db_tuned = Database(tdb_path)
for s, val in zip(syms, best["x"]):
    db_tuned.symbols[s] = float(val)
tuned_path = out / f"{args.prefix}-tuned.tdb"
db_tuned.to_file(str(tuned_path), if_exists="overwrite")
summary["tuned_tdb"] = tuned_path.name
(out / f"{args.prefix}-trace.json").write_text(json.dumps(trace, indent=1))
(out / f"{args.prefix}-summary.json").write_text(json.dumps(summary, indent=1))
print(json.dumps({k: summary[k] for k in summary if k != "params"}, indent=1), flush=True)
